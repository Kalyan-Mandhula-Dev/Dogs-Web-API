


CREATE TABLE breeds (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    VERSION INT NOT NULL,
    CREATED_AT DATETIME NOT NULL,
    MODIFIED_AT DATETIME NOT NULL,
    CONSTRAINT unique_breed_idx UNIQUE (NAME)
);

CREATE TABLE sub_breeds (
    ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    NAME VARCHAR(100) NOT NULL,
    BREED_ID BIGINT NOT NULL,
    VERSION INT NOT NULL,
    CREATED_AT DATETIME NOT NULL,
    MODIFIED_AT DATETIME NOT NULL,
    CONSTRAINT unique_sub_breed_idx UNIQUE (BREED_ID, NAME),
    CONSTRAINT fk_sub_breed_breed FOREIGN KEY (BREED_ID) REFERENCES breeds(ID)
                  ON DELETE CASCADE
);